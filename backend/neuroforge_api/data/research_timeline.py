"""Research timeline — landmark results in neuroscience, AI, and the bridge between them.

Every entry carries a DOI verified by scripts/verify_dois.py (Crossref, then
DataCite for arXiv). Entries without a DOI (books, un-registered conference
papers) say so explicitly. `significance` is a plain-language statement of
what the result established; it must not claim more than the paper does.

Categories:
    neuro   — a result about biological nervous systems
    ai      — a result about artificial systems
    bridge  — a result that explicitly links the two

`links` point into the multi-scale graph (neuroforge_api.data.scales) so a
timeline entry can be jumped to from — and to — the node it concerns.
"""

